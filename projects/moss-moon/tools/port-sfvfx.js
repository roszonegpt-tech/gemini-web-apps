#!/usr/bin/env node
// Converts the vendored Sprite Fusion TypeScript effects (art/vendor/spritefusion-vfx/*.ts, MIT) into ONE
// classic-script bundle: src/systems/sfvfx.js  ->  window.MM.sfvfx.<camelName> = factory(options)
// No dependencies: uses node:module.stripTypeScriptTypes (Node >= 22.13).
const fs = require('fs'), path = require('path'), { stripTypeScriptTypes } = require('node:module');
const root = path.resolve(__dirname, '..'), srcDir = path.join(root, 'art/vendor/spritefusion-vfx');
const out = path.join(root, 'src/systems/sfvfx.js');
const camel = s => s.replace(/-(\w)/g, (_, c) => c.toUpperCase());
const parts = [];
const names = fs.readdirSync(srcDir).filter(f => f.endsWith('.ts')).sort();
for (const file of names) {
  const name = file.replace(/\.ts$/, '');
  let js = stripTypeScriptTypes(fs.readFileSync(path.join(srcDir, file), 'utf8'), { mode: 'strip' });
  let factory = null;
  js = js.replace(/^export default function (\w+)/m, (_, n) => { factory = n; return 'function ' + n; });
  if (!factory) throw new Error('no default export in ' + file);
  js = js.replace(/^export (const|function|class|let) /gm, '$1 ');
  if (/^\s*(export|import)\s/m.test(js)) throw new Error('unhandled export/import in ' + file);
  const extras = [...js.matchAll(/^export /gm)].length; // none expected
  parts.push(`/* ---- ${name} ---- */\n(function(){\n${js.trim()}\nS['${camel(name)}']=${factory};\n})();\n`);
}
const header = `// GENERATED by tools/port-sfvfx.js from art/vendor/spritefusion-vfx/*.ts — do not edit.
// Pixel-art VFX by Sprite Fusion (https://www.spritefusion.com/pixel-art-vfx), MIT License, Copyright (c) 2026 Hugo Duprez.
// Each factory: MM.sfvfx.<name>(options) -> { update(dt), draw(frame, layer?), done() }.  ${names.length} effects.
'use strict';
(function(){
window.MM = window.MM || {};
const S = window.MM.sfvfx = window.MM.sfvfx || {};
`;
fs.writeFileSync(out, header + parts.join('\n') + '\n})();\n');
console.log('wrote', path.relative(root, out), (fs.statSync(out).size / 1024).toFixed(0) + ' KB,', names.length, 'effects');
